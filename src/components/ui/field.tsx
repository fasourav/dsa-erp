// layout="inset" is the Atrium form: on phones the fields sit in one rounded
// grouped list (label above a borderless 16px control, hairline separators);
// from md up it becomes a two-column grid of regular fields. Use <Field
// span="half"> for fields that share a desktop row.
function FieldGroup({
  className,
  layout = "stack",
  ...props
}: React.ComponentProps<"div"> & { layout?: "stack" | "inset" }) {
  return (
    <div
      data-slot="field-group"
      data-field-layout={layout}
      className={cn(
        "group/field-group @container/field-group flex w-full flex-col gap-5 data-[slot=checkbox-group]:gap-3 *:data-[slot=field-group]:gap-4",
        "data-[field-layout=inset]:gap-0 data-[field-layout=inset]:divide-y data-[field-layout=inset]:divide-border data-[field-layout=inset]:overflow-hidden data-[field-layout=inset]:rounded-3xl data-[field-layout=inset]:bg-field md:data-[field-layout=inset]:grid md:data-[field-layout=inset]:grid-cols-2 md:data-[field-layout=inset]:gap-4 md:data-[field-layout=inset]:divide-y-0 md:data-[field-layout=inset]:overflow-visible md:data-[field-layout=inset]:rounded-none md:data-[field-layout=inset]:bg-transparent",
        className
      )}
      {...props}
    />
  )
}

const fieldVariants = cva(
  "group/field flex w-full min-w-0 gap-2 data-[invalid=true]:text-destructive group-data-[field-layout=inset]/field-group:gap-0.5 group-data-[field-layout=inset]/field-group:px-4 group-data-[field-layout=inset]/field-group:py-2.5 group-data-[field-layout=inset]/field-group:transition-colors group-data-[field-layout=inset]/field-group:focus-within:bg-primary-tint md:group-data-[field-layout=inset]/field-group:col-span-2 md:group-data-[field-layout=inset]/field-group:gap-1.75 md:group-data-[field-layout=inset]/field-group:p-0 md:group-data-[field-layout=inset]/field-group:focus-within:bg-transparent md:group-data-[field-layout=inset]/field-group:data-[span=half]:col-span-1",
  {
    variants: {
      orientation: {
        vertical: "flex-col *:w-full [&>.sr-only]:w-auto",
        horizontal:
          "flex-row items-center has-[>[data-slot=field-content]]:items-start *:data-[slot=field-label]:flex-auto has-[>[data-slot=field-content]]:[&>[role=checkbox],[role=radio]]:mt-px",
        responsive:
          "flex-col *:w-full @md/field-group:flex-row @md/field-group:items-center @md/field-group:*:w-auto @md/field-group:has-[>[data-slot=field-content]]:items-start @md/field-group:*:data-[slot=field-label]:flex-auto [&>.sr-only]:w-auto @md/field-group:has-[>[data-slot=field-content]]:[&>[role=checkbox],[role=radio]]:mt-px",
      },
    },
    defaultVariants: {
      orientation: "vertical",
    },
  }
)

function Field({
  className,
  orientation = "vertical",
  span = "full",
  ...props
}: React.ComponentProps<"div"> &
  VariantProps<typeof fieldVariants> & { span?: "full" | "half" }) {
  return (
    <div
      role="group"
      data-slot="field"
      data-orientation={orientation}
      data-span={span}
      className={cn(fieldVariants({ orientation }), className)}
      {...props}
    />
  )
}

